import assert from 'node:assert/strict';
import {chromium} from '../frontend/node_modules/playwright/index.mjs';
const base=process.env.BENCH_URL || 'http://172.19.0.11';
const project=(await fetch(base+'/projects.json').then(r=>r.json())).find(p=>p.video);
const browser=await chromium.launch();
try {
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  await page.goto(base+'/projects/'+project.slug);
  await page.getByRole('button',{name:'Riproduci il video',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.film-player video').paused);
  await page.getByRole('button',{name:'Schermo intero',exact:true}).click();
  await page.waitForFunction(()=>!!document.fullscreenElement);
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.film-stage-toggle')).cursor==='none');
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.film-controls')).opacity==='0');
  await page.mouse.move(100,100);
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.film-stage-toggle')).cursor==='pointer');
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.film-controls')).opacity==='1');
  await page.locator('video').evaluate(v=>v.pause());
  const range=page.getByRole('slider',{name:'Avanzamento video'});
  const rect=await range.boundingBox();
  await page.mouse.move(rect.x+rect.width*.2,rect.y+rect.height/2);
  await page.mouse.down();
  const before=await range.inputValue();
  await page.mouse.move(rect.x+rect.width*.8,rect.y+rect.height/2,{steps:10});
  const after=await range.inputValue();
  assert.ok(Number(after)>Number(before),'rightward dragging must advance the video');
  await page.waitForTimeout(2800);
  assert.equal(await page.locator('.film-controls').evaluate(el=>getComputedStyle(el).opacity),'1','controls must remain visible while scrubbing');
  await page.mouse.up();
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.film-controls')).opacity==='0');
  await page.evaluate(()=>document.exitFullscreen());
  console.log('Desktop fullscreen: cursor and controls synchronized; timeline direction and drag retention passed');
  await page.close();

  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const mobile=await context.newPage();
  await mobile.goto(base+'/projects/'+project.slug);
  await mobile.getByRole('button',{name:'Riproduci il video',exact:true}).tap();
  await mobile.setViewportSize({width:844,height:390});
  await mobile.waitForTimeout(200);
  assert.ok(await mobile.locator('.film-player').evaluate(el=>el.getBoundingClientRect().height<=window.innerHeight-99));
  const rows=await mobile.locator('.film-controls').evaluate(el=>[...el.children].map(c=>{const r=c.getBoundingClientRect();return r.y+r.height/2}));
  assert.ok(Math.max(...rows)-Math.min(...rows)<1,'landscape controls must share one compact row');
  await mobile.getByRole('button',{name:'Schermo intero',exact:true}).tap();
  await mobile.waitForFunction(()=>!!document.fullscreenElement);
  const bounds=await mobile.locator('.film-player').boundingBox();
  assert.ok(Math.abs(bounds.width-844)<1 && Math.abs(bounds.height-390)<1);
  const session=await context.newCDPSession(mobile);
  await session.send('Emulation.setDeviceMetricsOverride',{width:390,height:844,screenWidth:390,screenHeight:844,deviceScaleFactor:1,mobile:true,screenOrientation:{type:'portraitPrimary',angle:0}});
  await mobile.waitForTimeout(200);
  const portrait=await mobile.locator('.film-player').boundingBox();
  assert.ok(Math.abs(portrait.width-390)<1 && Math.abs(portrait.height-844)<1);
  assert.equal(await mobile.locator('video').evaluate(v=>v.paused),false,'rotation must preserve playback');
  console.log('Mobile emulation: landscape layout, fullscreen resize and playback across rotation passed');
} finally {await browser.close()}
